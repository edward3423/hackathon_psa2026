"""The pinned benchmark: seed 42 must keep producing the committed result.

``fixtures/benchmark_golden.json`` is a whole ``BenchmarkResult`` for the
default configuration, regenerated by::

    uv run python scripts/run_benchmark.py --write-golden

which refuses to write anything but that configuration. Its purpose is to make
a change in the engine's numbers impossible to land silently: the diff on this
fixture is the change, spelled out day by day.

What is asserted here, and what deliberately is not
---------------------------------------------------
The HISTORICAL arm IS held to the recorded 7-day peak and 2-day recovered wait,
because it is a reconstruction that the fixture builder anchors to exactly
those two figures by construction. If it drifts off them the reconstruction is
broken.

The SIMULATED arms are NOT held to those anchors, and this file will not grow
an assertion that they approach them. The project's documented position is in
``BENCHMARK_NOTICE``: Singapore's recorded call and volume series measure
throughput, which congestion suppresses, so the simulation cannot reproduce the
recorded 2024 congestion and does not claim to. A test that demanded it would
be a standing invitation to tune the model until it passed, which is the exact
thing the benchmark's design exists to prevent. What is asserted instead is
that the gap stays published: every anchor row carries its recorded value, its
tolerance and the structural reason it lands where it does.
"""

import json
from pathlib import Path
from typing import Any

import pytest

from cascade.benchmark_run import DEFAULT_ARMS, default_world
from cascade.contracts import (
    BenchmarkConfig,
    BenchmarkResult,
    FleetArm,
    FleetBrainMode,
    SeriesProvenance,
)
from cascade.engine.fleet.benchmark import ANCHOR_TOLERANCES, run_benchmark
from cascade.fixtures import (
    CRISIS_ARRIVALS_FILE,
    CRISIS_GROUND_TRUTH_FILE,
    load_crisis_ground_truth,
    sha256_of,
)

ROOT = Path(__file__).resolve().parents[1]
GOLDEN_PATH = ROOT / "fixtures" / "benchmark_golden.json"
REGENERATE = "uv run python scripts/run_benchmark.py --write-golden"

#: The recorded anchors the reconstruction is built to hit exactly, and the
#: day the second one is anchored on. Restated from
#: scripts/build_crisis_fixture.py so a change there has to be made twice on
#: purpose rather than once by accident.
PEAK_WAIT_DAYS = 7.0
RECOVERED_WAIT_DAYS = 2.0
RECOVERY_ANCHOR_DATE = "2024-07-31"

#: A cold run pays about 30 seconds for the calibration search. That is slow
#: for a unit test and fast enough to stay in the default suite, which is where
#: it belongs: a golden nobody runs is a golden nobody maintains.
pytestmark = pytest.mark.slow


def pinned_config() -> BenchmarkConfig:
    """Exactly what ``--write-golden`` will accept, and nothing else."""
    return BenchmarkConfig(
        seed=42,
        arms=list(DEFAULT_ARMS),
        world=default_world(42),
        brain=FleetBrainMode.SCRIPTED,
    )


@pytest.fixture(scope="module")
def result() -> BenchmarkResult:
    """One benchmark run, shared by every test in this module."""
    return run_benchmark(pinned_config())


@pytest.fixture(scope="module")
def golden() -> dict[str, Any]:
    return dict(json.loads(GOLDEN_PATH.read_text(encoding="utf-8")))


def _comparable(result: BenchmarkResult) -> dict[str, Any]:
    """The result with wall-clock runtime zeroed, which is how it was pinned.

    ``runtime_ms`` is the only field in a ``BenchmarkResult`` that is not a
    function of the config and the fixtures, so it is the only one excluded.
    Nothing else is normalised away.
    """
    return dict(result.model_copy(update={"runtime_ms": 0}).model_dump(mode="json"))


def test_the_run_reproduces_the_committed_golden(
    result: BenchmarkResult, golden: dict[str, Any]
) -> None:
    produced = _comparable(result)
    if produced != golden:
        differing = sorted(
            key for key in produced.keys() | golden.keys() if produced.get(key) != golden.get(key)
        )
        pytest.fail(
            f"benchmark output drifted from {GOLDEN_PATH.name} in {differing}. If the "
            f"change is intended, regenerate with: {REGENERATE}"
        )


def test_the_golden_pins_the_documented_configuration(golden: dict[str, Any]) -> None:
    assert golden["config"] == pinned_config().model_dump(mode="json")
    assert golden["runtime_ms"] == 0, (
        f"runtime is wall-clock and must be pinned at 0 ({REGENERATE})"
    )


def test_the_golden_was_built_from_the_fixtures_on_disk(golden: dict[str, Any]) -> None:
    """A golden built from stale crisis data would pin the wrong numbers."""
    assert golden["fixture_hashes"] == {
        f"fixtures/{CRISIS_ARRIVALS_FILE}": sha256_of(CRISIS_ARRIVALS_FILE),
        f"fixtures/{CRISIS_GROUND_TRUTH_FILE}": sha256_of(CRISIS_GROUND_TRUTH_FILE),
    }


def test_cascade_beats_the_reactive_baseline_on_peak_wait(result: BenchmarkResult) -> None:
    """The one claim the benchmark stands behind: same world, different policy."""
    arms = {arm.arm: arm for arm in result.arms}
    baseline = arms[FleetArm.REACTIVE_BASELINE]
    cascade = arms[FleetArm.CASCADE_AGENTIC]

    assert cascade.metrics.peak_wait_days < baseline.metrics.peak_wait_days
    assert cascade.metrics.mean_wait_days < baseline.metrics.mean_wait_days

    comparison = next(item for item in result.comparisons if item.arm is FleetArm.CASCADE_AGENTIC)
    assert comparison.versus is FleetArm.REACTIVE_BASELINE
    assert comparison.wins_on_peak
    assert comparison.peak_wait_reduction_pct > 0.0


def test_both_simulated_arms_ran_the_same_calibrated_world(result: BenchmarkResult) -> None:
    """A win from a kinder parameter set would not be a win. Check there isn't one."""
    reports = [arm.calibration for arm in result.arms if arm.is_simulation]
    assert len(reports) == 2
    assert reports[0] is not None
    assert all(report == reports[0] for report in reports)
    assert reports[0].passed, reports[0].notes


def test_the_historical_arm_matches_its_own_recorded_anchors(result: BenchmarkResult) -> None:
    """The reconstruction is anchored to 7 days and 2 days, so it must hit them.

    This is the one arm an anchor assertion is fair on. It is not a simulation
    output: the fixture builder applies a single affine map chosen so the peak
    equals the recorded 7.0-day berthing delay and the 2024-07-31 value equals
    the recorded 2.0-day recovered wait. Failing here means the reconstruction
    no longer says what its method claims it says.
    """
    historical = next(arm for arm in result.arms if arm.arm is FleetArm.HISTORICAL)
    assert historical.provenance is SeriesProvenance.RECONSTRUCTED
    assert not historical.is_simulation
    assert historical.caveat

    assert historical.metrics.peak_wait_days == pytest.approx(PEAK_WAIT_DAYS, abs=1e-3)
    recovered = next(
        day for day in historical.daily if day.date.isoformat() == RECOVERY_ANCHOR_DATE
    )
    assert recovered.rolling_wait_days == pytest.approx(RECOVERED_WAIT_DAYS, abs=1e-3)

    recorded = {anchor.key: anchor.value for anchor in load_crisis_ground_truth().anchors}
    assert recorded["peak_berthing_delay_days"] == PEAK_WAIT_DAYS
    assert recorded["recovered_wait_days"] == RECOVERED_WAIT_DAYS


def test_the_historical_arm_invents_nothing_it_cannot_know(result: BenchmarkResult) -> None:
    """A wait curve knows nothing about vessels or port stay; it must not pretend."""
    historical = next(arm for arm in result.arms if arm.arm is FleetArm.HISTORICAL)
    assert historical.metrics.vessels_served == 0
    assert historical.metrics.mean_port_stay_hours == 0.0
    assert historical.decisions == []
    assert historical.calibration is None
    assert all(comparison.arm is not FleetArm.HISTORICAL for comparison in result.comparisons)


def test_the_anchor_gap_is_published_rather_than_scored(result: BenchmarkResult) -> None:
    """Anchor rows are context. Assert they are complete, not that they pass.

    Deliberately no assertion that any ``within_tolerance`` is True. See the
    module docstring and ``BENCHMARK_NOTICE``.
    """
    assert result.anchor_comparisons
    assert {anchor.anchor_key for anchor in result.anchor_comparisons} <= set(ANCHOR_TOLERANCES)
    for anchor in result.anchor_comparisons:
        assert anchor.recorded_provenance is SeriesProvenance.RECORDED
        assert anchor.interpretation, f"{anchor.anchor_key} must say why it lands where it does"
        assert anchor.tolerance == ANCHOR_TOLERANCES[anchor.anchor_key]
    assert "does not reproduce the recorded 2024 congestion" in result.notice
